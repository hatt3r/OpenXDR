package metrics

import (
	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
)

var (
	// ActiveAgents tracks the number of currently active agents.
	ActiveAgents = promauto.NewGaugeVec(
		prometheus.GaugeOpts{
			Name: "openxdr_active_agents",
			Help: "The number of currently active OpenXDR agents.",
		},
		[]string{"agent_id", "hostname", "os"},
	)

	// EventsReceived tracks telemetry events entering the gRPC server.
	EventsReceived = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "openxdr_events_received_total",
			Help: "The total number of telemetry events received by OpenXDR.",
		},
		[]string{"agent_id", "event_type"},
	)

	// EventsProcessed tracks events successfully or unsuccessfully processed.
	EventsProcessed = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "openxdr_events_total",
			Help: "The total number of processed telemetry events.",
		},
		[]string{"agent_id", "status"},
	)

	// AlertsGenerated tracks alerts generated by the detection engine.
	AlertsGenerated = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "openxdr_alerts_total",
			Help: "The total number of security alerts generated.",
		},
		[]string{"rule_id", "severity"},
	)

	// GRPCRequestsTotal tracks incoming gRPC requests.
	GRPCRequestsTotal = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "openxdr_grpc_requests_total",
			Help: "The total number of gRPC requests received by OpenXDR.",
		},
		[]string{"method", "status"},
	)
)
